from datetime import datetime, timedelta, timezone
from typing import Any, Dict, List


def now_iso(offset_minutes: int = 0) -> str:
    return (datetime.now(timezone.utc) + timedelta(minutes=offset_minutes)).isoformat()


def map_supabase_listing(row: Dict[str, Any]) -> Dict[str, Any]:
    kind = str(row.get("kind") or "service")
    modes = row.get("modes")
    return {
        "id": str(row.get("id")),
        "title": str(row.get("title") or ""),
        "description": str(row.get("description") or ""),
        "kind": kind,
        "modes": [str(m) for m in modes] if isinstance(modes, list) and modes else [kind],
        "category": str(row.get("category") or "General"),
        "priceLabel": row.get("price_label") or row.get("priceLabel") or None,
        "zoneName": str(row.get("zone_name") or row.get("zoneName") or "Centro Cívico"),
        "locationLabel": str(
            row.get("location_label") or row.get("locationLabel") or "Centro Cívico"
        ),
        "distanceKm": float(row.get("distance_km") if row.get("distance_km") is not None else 0.4),
        "x": float(row.get("map_x") if row.get("map_x") is not None else 50),
        "y": float(row.get("map_y") if row.get("map_y") is not None else 50),
        "image": row.get("image_url") or row.get("image") or None,
        "availability": str(row.get("availability") or "now"),
        "providerName": str(
            row.get("provider_name") or row.get("providerName") or "Vecino de la zona"
        ),
        "initials": str(row.get("provider_initials") or row.get("initials") or "NB"),
        "rating": float(row.get("rating") if row.get("rating") is not None else 4.9),
        "reviewCount": int(
            row.get("review_count") if row.get("review_count") is not None else 10
        ),
        "completedCount": int(
            row.get("completed_count") if row.get("completed_count") is not None else 15
        ),
        "approvalAuthor": row.get("approval_author") or row.get("approvalAuthor") or None,
        "approvalZone": row.get("approval_zone") or row.get("approvalZone") or None,
        "approvalNote": row.get("approval_note") or row.get("approvalNote") or None,
        "featured": bool(row.get("featured")),
        "isDemo": False,
    }


def map_supabase_interaction(row: Dict[str, Any], uid: str) -> Dict[str, Any]:
    return_flow = None
    if row.get("loan_due_at") is not None or row.get("borrower_confirmed") is not None:
        return_flow = {
            "dueAt": row.get("loan_due_at"),
            "borrowerConfirmed": bool(row.get("borrower_confirmed")),
            "lenderConfirmed": bool(row.get("lender_confirmed")),
        }
    return {
        "id": str(row.get("id")),
        "summary": str(row.get("summary") or ""),
        "type": str(row.get("type") or "service"),
        "status": str(row.get("status") or "requested"),
        "syncState": "confirmed",
        "listingTitle": str(row.get("listing_title") or "Publicación"),
        "updatedAt": row.get("updated_at") or row.get("created_at") or now_iso(),
        "role": "provider" if str(row.get("provider_id")) == uid else "requester",
        "returnFlow": return_flow,
    }


